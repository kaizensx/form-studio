"""Regenerate docs/MCP.md from the live tool definitions, so the reference cannot drift."""
import asyncio
import inspect
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from form import mcp_server  # noqa: E402


def main():
    m = mcp_server.build()
    tools = asyncio.run(m.list_tools())
    lines = ["# FORM MCP tools", "", "Generated by `scripts/gen_mcp_docs.py` from the server itself.", "",
             "Server instructions (sent to every client):", "", "```", mcp_server.INSTRUCTIONS.strip(), "```", ""]
    for t in tools:
        ro = t.annotations and t.annotations.read_only_hint
        lines += [f"## `{t.name}`" + ("  · read-only" if ro else ""), "", inspect.cleandoc(t.description or ""), ""]
        props = (t.input_schema or {}).get("properties", {})
        req = set((t.input_schema or {}).get("required", []))
        if props:
            lines += ["| Argument | Type | Required |", "|---|---|---|"]
            for k, v in props.items():
                typ = v.get("type") or " | ".join(x.get("type", "?") for x in v.get("anyOf", []))
                lines.append(f"| `{k}` | {typ} | {'yes' if k in req else ''} |")
            lines.append("")
    lines += ["## Prompt `design_part(goal)`", "", "A guided session: measure first, look at renders, preview before commit, hand release to the user.", ""]
    out = Path(__file__).resolve().parents[1] / "docs" / "MCP.md"
    out.write_text("\n".join(lines))
    print(out, len(tools), "tools")


if __name__ == "__main__":
    main()

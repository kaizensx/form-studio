def mask_sizes(V: np.ndarray) -> dict:
    """The distances the runner's masks read the high poly over (mm), from the asset's size: the edge (Bevel)
    radius, the cavity AO distance and the thickness AO distance."""
    d = float(np.linalg.norm(np.ptp(np.asarray(V, float), axis=0))) or 1.0
    return {"edge_mm": round(min(max(d * 0.006, 0.25), 15.0), 4), "cavity_mm": round(min(max(d * 0.03, 1.0), 120.0), 4),
            "thick_mm": round(min(max(d * 0.04, 1.0), 160.0), 4)}


def _high_arrays(hc: meshsource.CageData, cage: meshsource.CageData, face_mat: list, mats: list, off, hl: int):
    """The high-only cage as runner arrays, its faces given the material of the region they name, else of the
    nearest low-cage face; and its subdivision level (so it has about the triangles the plain high poly would)."""
    fm = np.full(len(hc.F), -1, np.int64)
    by_name = {name: (face_mat[fs[0]] if fs else 0) for name, fs in cage.regions.items()}
    for name, fs in hc.regions.items():
        if name in by_name:
            fm[fs] = by_name[name]
    if (fm < 0).any():
        cl = np.array([np.mean(cage.V[f], axis=0) for f in cage.F])
        ch = np.array([np.mean(hc.V[f], axis=0) for f in hc.F])
        miss = np.nonzero(fm < 0)[0]
        fmat = np.asarray(face_mat, np.int64)
        for s in range(0, len(miss), 2048):
            m = miss[s:s + 2048]
            d = np.linalg.norm(ch[m][:, None, :] - cl[None, :, :], axis=2)
            fm[m] = fmat[np.argmin(d, axis=1)]
    ratio = max(len(hc.F) / max(len(cage.F), 1), 1.0)
    level = int(max(0, min(hl, round(hl - np.log(ratio) / np.log(4)))))
    arrays = {"V": hc.V + off, "F_flat": np.array([i for f in hc.F for i in f], np.int64),
              "F_len": np.array([len(f) for f in hc.F], np.int64),
              "crease_e": np.array([[a, b] for a, b, _ in hc.creases], np.int64).reshape(-1, 2),
              "crease_s": np.array([s for *_, s in hc.creases], np.float64),
              "face_region": np.zeros(0, np.int64), "face_mat": fm}
    return arrays, max(level, 1)


# ---- Blender's lifetime: never outlive Form Studio, never leave work folders ---------------------------------

_LIVE: dict = {}                     # pid -> Popen of every Blender this process started and has not seen end
_LIVE_LOCK = threading.Lock()
OWNER = "owner.json"


def _kill_group(pid: int) -> None:
    try:
        if os.name != "nt":
            os.killpg(pid, signal.SIGKILL)
        else:
            os.kill(pid, signal.SIGTERM)
    except (OSError, ProcessLookupError):
        pass


def kill_all() -> int:
    """Stop every Blender this process started (registered with atexit, so a Form Studio that quits mid-bake takes
    its Blender with it; a hard kill is covered by the runner's own parent watch). Returns how many were stopped."""
    with _LIVE_LOCK:
        procs = list(_LIVE.values())
        _LIVE.clear()
    n = 0
    for p in procs:
        if p.poll() is None:
            _kill_group(p.pid)
            n += 1
    return n


atexit.register(kill_all)


def _alive(pid: int) -> bool:
    if not pid or pid <= 0:
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    except OSError:
        return False
    return True


def _write_owner(work: Path, blender_pid: int | None = None) -> None:
    try:
        (work / OWNER).write_text(json.dumps({"pid": os.getpid(), "blender_pid": blender_pid,
                                              "started": time.time()}), encoding="utf-8")
    except OSError:
        pass


def cleanup_stale(base) -> list[str]:
    """Remove form-game-* work folders (and .old-<pid> leftovers) in base whose owning process is gone: a Form
    Studio that was killed mid-build leaves them. A Blender such a folder names is stopped first if it still runs
    (A3, A8). Folders of a live process (the app and an MCP server can build at once) are left alone; a folder with
    no owner file is removed only when older than the pipeline's timeout. Returns the names removed."""
    base = Path(base)
    out = []
    if not base.is_dir():
        return out
    now = time.time()
    for d in base.iterdir():
        if not d.is_dir():
            continue
        if d.name.startswith("form-game-"):
            try:
                own = json.loads((d / OWNER).read_text(encoding="utf-8"))
            except (OSError, ValueError):
                own = None
            if own is None:
                try:
                    if now - d.stat().st_mtime < TIMEOUT_S + 600:
                        continue
                except OSError:
                    continue
            elif _alive(int(own.get("pid") or 0)):
                continue
            else:
                bp = int(own.get("blender_pid") or 0)
                if bp and _alive(bp) and _is_blender(bp):
                    _kill_group(bp)
        elif ".old-" in d.name:
            try:
                if _alive(int(d.name.rsplit(".old-", 1)[1])):
                    continue
            except ValueError:
                continue
        else:
            continue
        shutil.rmtree(d, ignore_errors=True)
        out.append(d.name)
    return out


def _is_blender(pid: int) -> bool:
    """Is pid a Blender process (so a recycled pid is never killed)?"""
    if os.name == "nt":
        return False
    try:
        r = subprocess.run(["ps", "-o", "command=", "-p", str(int(pid))], capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return False
    return "blender" in r.stdout.lower() and "blender_game.py" in r.stdout


def weld_mesh(V: np.ndarray, T: np.ndarray, fm: np.ndarray, tol_mm: float = 1e-4):
    """Points within tol_mm merged and triangles that collapse dropped: a CAD tessellation is one patch per face, and
    decimating unwelded patches opens cracks. Returns (V, T, face material, points merged)."""
    key = np.round(V / tol_mm).astype(np.int64)
    _, first, inv = np.unique(key, axis=0, return_index=True, return_inverse=True)
    T2 = inv.reshape(-1)[T]
    keep = (T2[:, 0] != T2[:, 1]) & (T2[:, 1] != T2[:, 2]) & (T2[:, 0] != T2[:, 2])
    return V[first], T2[keep], fm[keep], int(len(V) - len(first))


def _face_region(cage: meshsource.CageData) -> np.ndarray:
    r = np.full(len(cage.F), -1, np.int64)
    for k, name in enumerate(sorted(cage.regions)):
        r[cage.regions[name]] = k
    return r if cage.regions else np.zeros(0, np.int64)


def _surface_samples(UV: np.ndarray, T: np.ndarray, n: int = 200_000, seed: int = 0) -> np.ndarray:
    """n points spread over a LOD's UV triangles in proportion to their UV area (fixed seed: the same map gives the
    same number). (n, 2), Blender's convention (v up)."""
    U = np.asarray(UV, dtype=np.float64)[np.asarray(T)]
    e1, e2 = U[:, 1] - U[:, 0], U[:, 2] - U[:, 0]
    area = np.abs(e1[:, 0] * e2[:, 1] - e1[:, 1] * e2[:, 0]) / 2
    if not len(U) or area.sum() <= 0:
        return np.zeros((0, 2))
    rng = np.random.default_rng(seed)
    k = rng.choice(len(U), size=n, p=area / area.sum())
    a, b = rng.random(n), rng.random(n)
    flip = a + b > 1
    a[flip], b[flip] = 1 - a[flip], 1 - b[flip]
    return U[k, 0] + a[:, None] * e1[k] + b[:, None] * e2[k]


def normal_detail(rgb: np.ndarray, UV: np.ndarray, T: np.ndarray) -> dict:
    """How much a baked tangent-space normal map says beyond "flat": the standard deviation of its blue channel
    (0..1) over LOD0's surface, area-weighted, and of red and green. A map baked from a high poly that is only the
    low poly subdivided is near constant blue (the "flat blue" map); material height and real high-poly detail
    raise it."""
    rgb = np.asarray(rgb, dtype=np.float64)
    h, w = rgb.shape[:2]
    pts = _surface_samples(UV, T)
    if not len(pts):
        return {"blue_std": 0.0, "rg_std": 0.0}
    x = np.clip((pts[:, 0] * w).astype(int), 0, w - 1)
    y = np.clip(((1 - pts[:, 1]) * h).astype(int), 0, h - 1)
    px = rgb[y, x, :3]
    return {"blue_std": round(float(px[:, 2].std()), 5), "rg_std": round(float(px[:, :2].std(axis=0).mean()), 5)}


def uv_islands(P: np.ndarray, UV: np.ndarray, T: np.ndarray) -> np.ndarray:
    """An island id per triangle: triangles that share an edge in 3D and in UV (a corner welded by position and UV,
    so a split normal does not cut an island; a UV seam does)."""
    key = np.concatenate([np.round(np.asarray(P, float), 4), np.round(np.asarray(UV, float), 6)], axis=1)
    _, wid = np.unique(key, axis=0, return_inverse=True)
    Tw = wid.reshape(-1)[np.asarray(T)]
    n = len(Tw)
    E = np.concatenate([np.sort(Tw[:, [0, 1]], 1), np.sort(Tw[:, [1, 2]], 1), np.sort(Tw[:, [2, 0]], 1)])
    tri = np.tile(np.arange(n), 3)
    o = np.lexsort((E[:, 1], E[:, 0]))
    Es, ts = E[o], tri[o]
    same = np.all(Es[1:] == Es[:-1], axis=1)
    parent = np.arange(n)

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    for a, b in zip(ts[:-1][same], ts[1:][same]):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[max(ra, rb)] = min(ra, rb)
    roots = np.array([find(i) for i in range(n)])
    return np.unique(roots, return_inverse=True)[1].reshape(-1)


def island_texel(P_mm: np.ndarray, UV: np.ndarray, T: np.ndarray, px: int) -> dict:
    """Texel density per UV island (texture px per metre: sqrt(UV area / surface area) x px), against the median
    island. "worst" is the largest relative distance from the median; "outside" counts islands beyond ISLAND_TEXEL_TOL
    and "outside_area" is their share of the surface."""
    P = np.asarray(P_mm, float) * 0.001
    T = np.asarray(T)
    lab = uv_islands(P_mm, UV, T)
    a3 = 0.5 * np.linalg.norm(np.cross(P[T[:, 1]] - P[T[:, 0]], P[T[:, 2]] - P[T[:, 0]]), axis=1)
    u = np.asarray(UV, float)[T]
    du, dv = u[:, 1] - u[:, 0], u[:, 2] - u[:, 0]
    a2 = 0.5 * np.abs(du[:, 0] * dv[:, 1] - du[:, 1] * dv[:, 0])
    n = int(lab.max()) + 1 if len(lab) else 0
    S3, S2 = np.bincount(lab, a3, n), np.bincount(lab, a2, n)
    ok = S3 > 0
    if not ok.any():
        return {"islands": 0, "median": 0.0, "worst": 0.0, "outside": 0, "outside_area": 0.0}
    d = np.sqrt(S2[ok] / S3[ok]) * px
    med = float(np.median(d))
    rel = np.abs(d / med - 1) if med > 0 else np.zeros_like(d)
    bad = rel > ISLAND_TEXEL_TOL
    return {"islands": int(ok.sum()), "median": round(med, 2), "min": round(float(d.min()), 2),
            "max": round(float(d.max()), 2), "worst": round(float(rel.max()), 4), "outside": int(bad.sum()),
            "outside_area": round(float(S3[ok][bad].sum() / S3[ok].sum()), 5)}


def normal_detail_of(stage: Path, asset: str) -> dict | None:
    """normal_detail() of a built asset's map against LOD0, with the floor: a measure, not a check (a plain smooth
    plastic part honestly bakes a flat map; the game bench holds its assets to the floor)."""
    png, lod0 = stage / "textures" / f"{asset}_normal.png", stage / "lods" / "lod0.npz"
    if not (png.is_file() and lod0.is_file()):
        return None
    from PIL import Image
    z = np.load(lod0, allow_pickle=False)
    rgb = np.asarray(Image.open(png).convert("RGB"), dtype=np.float64) / 255.0
    nd = normal_detail(rgb, z["UV"], z["T"])
    return {**nd, "floor": NORMAL_BLUE_STD_MIN, "above_floor": nd["blue_std"] >= NORMAL_BLUE_STD_MIN,
            "evidence": "computed"}


def _normal_checks(stage: Path, asset: str, px: int | None = None) -> list[dict]:
    """The baked normal map against LOD0's UVs (validate.normal_map_check) and the texel density of each UV island,
    when the map and LOD0 are there."""
    png, lod0 = stage / "textures" / f"{asset}_normal.png", stage / "lods" / "lod0.npz"
    out = []
    if not lod0.is_file():
        return out
    z = np.load(lod0, allow_pickle=False)
    if png.is_file():
        out.append(vmod.normal_map_check(png.read_bytes(), z["UV"], z["T"]))
    if px:
        it = island_texel(z["P"], z["UV"], z["T"], int(px))
        out.append({"id": "texel_islands", "label": "Every UV island has the median texel density",
                    "status": "PASS" if it["outside"] == 0 else "FAIL",
                    "value": f"{it['islands']} islands, worst {it['worst'] * 100:.1f}% from the median "
                             f"{it['median']:.0f} px/m; {it['outside']} outside",
                    "detail": f"Per island sqrt(UV area / surface area) x texture size, within "
                              f"±{ISLAND_TEXEL_TOL * 100:g}% of the median island (proposed).",
                    "evidence": "computed", "lod": 0})
    return out


def revalidate(out_dir) -> dict:
    """validate.validate on a built asset's GLB again, with the budgets and texture size it was built with, and the
    baked normal map against LOD0's UVs."""
    out_dir = Path(out_dir)
    rep = json.loads((out_dir / "report.json").read_text(encoding="utf-8"))
    v = vmod.validate((out_dir / f"{rep['asset']}.glb").read_bytes(), rep["budgets"], rep["texture_px"],
                      expect_size_mm=rep["size_mm"])
    v["checks"] += _normal_checks(out_dir, rep["asset"], rep.get("texture_px"))
    v["ok"] = all(c["status"] == "PASS" for c in v["checks"])
    return v


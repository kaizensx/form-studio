"""Form Studio's kitbash kit: original parametric detail parts (bolts, rivets, vents, hinges, straps, grips, ...).

Every part is generated by code from a few numbers; nothing is downloaded or copied. A part is a small closed
subdivision cage (quads where it can, flat polygon caps elsewhere, creases on its hard edges) with its pivot at the
origin and +Z as the direction it stands out along (parts.py says what each kind of part means by that).

    from form.game import kit
    kit.names()                              # the part names
    kit.describe()                           # {name: {kind, params: {p: [default, lo, hi, "int"|"mm"]}, doc}}
    p = kit.build("bolt_hex", {"across_flats": 10})
    p.V, p.F, p.C                            # points (mm), polygons, creases [[a, b, weight], ...]

The model_mesh op kit_place puts parts on a cage (form/adapters/blender_model.py): it checks the part's numbers
here, builds the part, scales it, turns it about +Z, and sends the geometry to Blender's fixed runner, which puts
+Z on the surface normal. Plain numpy: no Blender, no OCCT.
"""
from __future__ import annotations

import math

from .geom import Shell, closed_and_oriented, shells, volume  # noqa: F401
from .parts import EMBED, PARTS  # noqa: F401

KIT_VERSION = 1              # part of every kit_place op key: a change to any part's geometry bumps it


class KitError(ValueError):
    pass


def names() -> list[str]:
    return sorted(PARTS)


def describe() -> dict:
    return {k: {"kind": PARTS[k][1],
                "params": {p: [d, lo, hi, "int" if integer else "mm"]
                           for p, (d, lo, hi, integer) in PARTS[k][2].items()},
                "doc": PARTS[k][3]} for k in names()}


def check_params(name: str, params: dict | None) -> dict:
    """The part's numbers with defaults filled in, or KitError naming what is wrong."""
    if name not in PARTS:
        raise KitError(f"no kit part named {str(name)[:40]!r}. Parts: {', '.join(names())}.")
    spec = PARTS[name][2]
    params = params or {}
    if not isinstance(params, dict):
        raise KitError(f"{name}: params must be an object.")
    extra = set(params) - set(spec)
    if extra:
        raise KitError(f"{name} does not take {', '.join(sorted(map(str, extra)))}. It takes: {', '.join(spec)}.")
    out = {}
    for p, (d, lo, hi, integer) in spec.items():
        v = params.get(p, d)
        if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v):
            raise KitError(f"{name}.{p} must be a number.")
        if integer and not float(v).is_integer():
            raise KitError(f"{name}.{p} must be a whole number.")
        if not lo <= v <= hi:
            raise KitError(f"{name}.{p} = {v} is outside {lo:g}..{hi:g}.")
        out[p] = int(v) if integer else float(v)
    return out


def build(name: str, params: dict | None = None) -> Shell:
    """The part at scale 1 in its own frame (pivot at the origin)."""
    p = check_params(name, params)
    try:
        s = PARTS[name][0](p)
    except ValueError as e:
        raise KitError(str(e)) from None
    return Shell(s.V.round(6) + 0.0, s.F, sorted(s.C))

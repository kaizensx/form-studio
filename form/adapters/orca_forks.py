"""OrcaSlicer forks that kept its CLI, preset layout and 3MF output: one adapter shape, several programs.

A fork qualifies only when its own source, at the release FORM was tested with, still defines the CLI options
FORM passes (src/libslic3r/PrintConfig.cpp CLIActionsConfigDef / CLIMiscConfigDef: --load-settings,
--load-filaments, --arrange, --slice, --export-3mf, --outputdir) and still writes <outputdir>/plate_<n>.gcode.
Everything else (presets as JSON under <config>/system/<vendor>/ and <config>/user/<id>/, the selection in
<App>.conf, the build plate, the exit codes) is OrcaSlicer's and handled in _bbl.py and orca.py.

    ElegooSlicer 1.5.3.5   github.com/ELEGOO-3D/ElegooSlicer   (Orca 2.4.2 based)  src/ElegooSlicer.cpp
    Snapmaker Orca 2.4.1   github.com/Snapmaker/OrcaSlicer       src/Snapmaker_Orca.cpp

Both were run for real on macOS (arm64): the official DMG copied out of its disk image, never opened, a cube
sliced with each program's own presets. Creality Print 7 is not one of them: its CLI needs --cli, has no
--arrange or --export-3mf and writes no slice_info (src/slic3r/CLI/SliceCommand.cpp, tag v7.3.1).

`--help` prints the Orca version the fork is based on (ElegooSlicer) or an internal number (Snapmaker Orca
"01.10.01.50"), not the program's own version. The version comes from the app bundle (macOS Info.plist), else
from the G-code a slice writes ("; generated by ElegooSlicer 1.5.3.5").
"""
from __future__ import annotations

import plistlib
import shutil
import types
from pathlib import Path

from . import _bbl, orca
from .common import first_dir, find_app as _find, platform, shipped_dirs
from .common import parse_layers as _parse_layers


def _plist_version(app: str) -> str:
    """CFBundleShortVersionString of a macOS app bundle the program sits in ("" elsewhere)."""
    try:
        p = Path(app).resolve()
        for parent in p.parents:
            if parent.suffix == ".app":
                with open(parent / "Contents" / "Info.plist", "rb") as f:
                    return str(plistlib.load(f).get("CFBundleShortVersionString") or "")
    except (OSError, ValueError, plistlib.InvalidFileException):
        pass
    return ""


def make(kind: str, label: str, *, program: str, share: str, conf_name: str, apps: dict, config_dirs: dict, url: str,
         brew: str = "", winget: str = "", flatpak: str = "", size: str = "", notes: str = "") -> types.SimpleNamespace:
    """An adapter module's functions for one fork. `program` is the name in its G-code header ("ElegooSlicer")."""
    fam = _bbl.Family(kind=kind, label=label, conf_name=conf_name, version_re=r"(?!)", program=program, table=kind,
                      deep_search=True, parse_header=orca.parse_gcode_header,
                      cache_dirs=lambda app, cdir: [d for d in [Path(cdir) / "system", *shipped_dirs(app, share)] if d.is_dir()],
                      shipped=lambda app: shipped_dirs(app, share), selection=orca.selection,
                      exit_reasons=orca.EXIT_REASONS, bed_type=orca.bed_type)

    def settings(cfg: dict) -> dict:
        s = cfg["slicer"]
        sub = s.get(kind) if isinstance(s.get(kind), dict) else {}
        explicit = s.get("kind") == kind
        out = {k: sub.get(k) or (s.get(k, "auto") if explicit else "auto") for k in ("machine", "process", "filament")}
        out["app"], out["config_dir"] = sub.get("app") or "", sub.get("config_dir") or ""
        return out

    def find_app(cfg: dict) -> str | None:
        st = settings(cfg)
        return _find([st["app"]]) if st["app"] else _find(apps[platform()])

    def config_dir(cfg: dict) -> Path:
        st = settings(cfg)
        return Path(first_dir([st["config_dir"]] if st["config_dir"] else config_dirs[platform()]))

    def install_hint() -> dict:
        cmds = []
        if platform() == "darwin" and brew and shutil.which("brew"):
            cmds = [f"brew install --cask {brew}"]
        elif platform() == "win" and winget and shutil.which("winget"):
            cmds = [f"winget install --id {winget} -e"]
        return {"url": url, "cmds": cmds, "note": f"Download from {url}", "size": size}

    def resolve(cfg: dict) -> dict:
        st = settings(cfg)
        app = find_app(cfg)
        shown = Path(app or st["app"] or apps[platform()][0]).expanduser()
        out = _bbl.resolve(fam, cfg["slicer"], shown, config_dir(cfg), st)
        if not app:
            out["reason"] = (f"{label} was not found (looked for {apps[platform()][0]}). "
                             f"Install it or set [slicer.{kind}].app in studio.toml.")
        return out

    def version(app: str) -> str:
        if app not in fam.version_cache:
            v = _plist_version(app)
            fam.version_cache[app] = v or _bbl.version(fam, app)
        return fam.version_cache[app]

    def public(resolved: dict) -> dict:
        out = {k: v for k, v in resolved.items() if k != "presets"}
        out["presets"] = {k: {"name": v["name"], "sha": v["sha"]} for k, v in resolved.get("presets", {}).items()}
        if resolved.get("available"):
            out["version"] = version(resolved["app"])
        return out

    def slice_stl(resolved: dict, stl: Path, out_dir: Path, timeout: float = 600) -> dict:
        version(resolved["app"])                       # the bundle's version before the G-code's, when there is one
        return _bbl.slice_stl(fam, resolved, stl, out_dir, timeout)

    def parse_layers(path: Path) -> list[dict]:
        return _parse_layers(path, "auto")

    return types.SimpleNamespace(LABEL=label, URL=url, FAMILY=fam, APPS=apps, CONFIG_DIRS=config_dirs, BREW=brew, WINGET=winget,
                                 FLATPAK=flatpak, SIZE=size, NOTES=notes, settings=settings, find_app=find_app,
                                 config_dir=config_dir, install_hint=install_hint, resolve=resolve, version=version,
                                 public=public, slice_stl=slice_stl, parse_layers=parse_layers,
                                 parse_gcode_header=orca.parse_gcode_header)



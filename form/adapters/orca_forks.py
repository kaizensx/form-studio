def export(ns: types.SimpleNamespace, module_globals: dict) -> None:
    """Give an adapter module (elegoo.py, snapmaker.py) the module-level names form/adapters/__init__.py describes."""
    for name in ("LABEL", "URL", "FAMILY", "APPS", "CONFIG_DIRS", "find_app", "config_dir", "install_hint", "resolve",
                 "version", "public", "slice_stl", "parse_layers", "parse_gcode_header"):
        module_globals[name] = getattr(ns, name)
    module_globals["settings"] = ns.settings

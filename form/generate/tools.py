"""Mesh generation over MCP: mesh_generators (what is set up) and generate_mesh (generate, then rebuild as CAD).

generate_mesh never sends anything on an agent's say-so. For a hosted generator it shows the person a confirmation
card with the disclosure (what is sent, to which host, billed to whom) in Form Studio's chat, or the client's own
form (MCP elicitation); it runs only on their yes. Turning a generator on and storing its key are the person's, in
Settings or the CLI; no tool here does either."""
from __future__ import annotations

from mcp.server.mcpserver import Context


def register_tools(mcp, studio, run_async, RO, RW, made=None) -> None:

    from ..studio import StudioError
    from . import GenerateError, disclose, make, providers

    def _err(e: GenerateError):
        return StudioError(str(e), e.hint, status=e.status)

    @mcp.tool(annotations=RO)
    async def mesh_generators() -> dict:
        """List the mesh generators (TRELLIS.2 on this computer; Meshy and Tripo on the person's own key; Hunyuan,
        listed but not wired) with whether each is ready and what it needs. There is no default: when none is ready,
        say so and point to Settings > Engines; never set one up yourself."""
        st = studio()
        return await run_async(providers, st.cfg)

    @mcp.tool(annotations=RW)
    async def generate_mesh(provider: str, text: str = "", image: str = "", size_mm: float = 80.0,
                            tolerance: float = 0.05, name: str = "", ctx: Context = None) -> dict:
        """Generate a mesh from words or a picture (an absolute path) with a generator the person set up, then rebuild
        it as an editable design: split into parts at its concave creases and triaged, each part rebuilt (parametric
        where it can be; an organic part keeps verified surfaces) with its deviation map, labelled "generated by
        <provider>/<model>"; split lists each part's class, layer, editable share and distance. The mesh is a reference, never the design; its size is assumed (longest side
        size_mm). Before a hosted run the person sees what is sent and to whom, and confirms; without their yes
        nothing is sent ({ran: false}). Several minutes."""
        from .. import ask as ask_mod
        from .. import elicit
        st = studio()
        try:
            d = await run_async(disclose, st.cfg, provider, text or None, image or None)
        except GenerateError as e:
            raise _err(e) from None
        if not d["ready"]:
            return {"ran": False, "why": d["why"], "disclosure": d}
        if d["kind"] == "hosted":
            q = ask_mod.question(d["text"] + " Send it?", ["Send it", "Do not send"], False, False,
                                 f"generate_mesh with {d['title']}", "confirm")
            a = await elicit.ask(ctx, q)
            yes = a.get("answered") and (a.get("choices") or [a.get("answer")])[0] == "Send it"
            if not yes:
                return {"ran": False, "why": "The person did not agree to send it, or could not be asked. Nothing was sent.",
                        "disclosure": d, "asked": a}
        try:
            out = await run_async(make, st, provider, text or None, image or None, d["consent"], size_mm, tolerance, name)
        except GenerateError as e:
            raise _err(e) from None
        if made is not None:
            made(out["project"], "generate_mesh", ctx)
        return {"ran": True, **out}

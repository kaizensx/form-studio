_EXTRA: dict = {}                 # providers registered at run time (the test fixture); never persisted


def register(provider: Provider, runner) -> None:
    """Add a provider for this process only (tests). runner(provider, text, image, out_dir, cfg) -> mesh path."""
    PROVIDERS[provider.id] = provider
    _EXTRA[provider.id] = runner


def unregister(pid: str) -> None:
    _EXTRA.pop(pid, None)
    PROVIDERS.pop(pid, None)


# ---- the person's settings ----------------------------------------------------------------------------------------

def _settings_path(cfg) -> Path:
    return Path(cfg["data"]["dir"]).expanduser() / ".generate" / "settings.json"


def settings(cfg) -> dict:
    try:
        d = json.loads(_settings_path(cfg).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        d = {}
    return {"enabled": list(d.get("enabled") or []), "trellis2": dict(d.get("trellis2") or {})}


def _save(cfg, d: dict) -> None:
    from .. import fsutil
    p = _settings_path(cfg)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(".tmp")
    tmp.write_text(json.dumps(d, indent=1), encoding="utf-8")
    fsutil.replace(tmp, p)


def enable(cfg, pid: str, on: bool = True) -> dict:
    """Turn a generator on or off. A person's decision: the CLI, the app's Settings; never an agent's tool."""
    get(pid)
    d = settings(cfg)
    en = [x for x in d["enabled"] if x != pid] + ([pid] if on else [])
    d["enabled"] = en
    _save(cfg, d)
    return status(cfg, pid)


def set_trellis(cfg, folder: str, python: str = "") -> dict:
    """Point Form Studio at a TRELLIS.2 checkout the person installed: reads its LICENSE and records it."""
    root = Path(folder).expanduser().resolve()
    lic = root / "LICENSE"
    if not (root / "trellis2").is_dir() or not lic.is_file():
        raise GenerateError(f"{root} is not a TRELLIS.2 checkout (no trellis2/ package or LICENSE).",
                            "Clone https://github.com/microsoft/TRELLIS.2 and run its setup.sh, then give its folder.")
    text = lic.read_text(encoding="utf-8", errors="replace")
    if "MIT License" not in text[:200] and "Permission is hereby granted, free of charge" not in text:
        raise GenerateError("The LICENSE in that folder is not the MIT licence TRELLIS.2 is released under.",
                            "Form Studio runs TRELLIS.2 only under the licence it checked. Use an unmodified checkout.")
    py = Path(python).expanduser() if python else _conda_python("trellis2")
    if py is None or not Path(py).exists():
        raise GenerateError("No Python for the TRELLIS.2 environment was found.",
                            "Give python= the interpreter of its conda env (e.g. ~/miniconda3/envs/trellis2/bin/python).")
    rec = {"folder": str(root), "python": str(py), "licence": "MIT", "licence_sha256": hashlib.sha256(text.encode()).hexdigest(),
           "licence_first_line": text.strip().splitlines()[0][:80], "checked": time.strftime("%Y-%m-%d %H:%M:%S")}
    d = settings(cfg)
    d["trellis2"] = rec
    _save(cfg, d)
    return status(cfg, "trellis2")


def _conda_python(env: str) -> str | None:
    for base in ("~/miniconda3", "~/anaconda3", "~/miniforge3", "~/mambaforge", "/opt/conda"):
        p = Path(base).expanduser() / "envs" / env / "bin" / "python"
        if p.exists():
            return str(p)
    return None


def _gpu() -> str:
    """The NVIDIA GPUs nvidia-smi reports, or ""."""
    exe = shutil.which("nvidia-smi")
    if not exe:
        return ""
    try:
        r = subprocess.run([exe, "--query-gpu=name,memory.total", "--format=csv,noheader"], capture_output=True,
                           text=True, timeout=10)
        return r.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


def get(pid: str) -> Provider:
    p = PROVIDERS.get(str(pid))
    if p is None:
        raise GenerateError(f"No mesh generator “{pid}”.", "Generators: " + ", ".join(PROVIDERS) + ".", 404)
    return p


def status(cfg, pid: str) -> dict:
    """{id, ..., enabled, ready, why}: whether it can run now, and what it needs when it cannot."""
    p = get(pid)
    s = settings(cfg)
    out = {**p.public(), "enabled": pid in s["enabled"] or pid in _EXTRA, "ready": False, "why": ""}
    if pid in _EXTRA:
        out.update(ready=True, why="A test fixture registered in this process.")
        return out
    if not p.implemented:
        out["why"] = p.requirements + " " + p.note
        return out
    if p.kind == "hosted":
        from .. import secrets
        key, _where = secrets.value(p.secret)
        if not key:
            out["why"] = f"No {p.title} API key. Store yours in Settings › Agents & models (or `form secrets set {p.secret}`)."
        elif not out["enabled"]:
            out["why"] = f"Off. Turn it on in Settings › General › Engines, or `form generate enable {pid}`."
        else:
            out.update(ready=True, why=f"On, with your key. Each run is billed to your {p.title} account.")
        return out
    t = s["trellis2"]
    if not t:
        out["why"] = "Not set up. " + p.requirements
    elif not Path(t.get("python", "")).exists() or not Path(t.get("folder", "")).is_dir():
        out["why"] = "The TRELLIS.2 folder or its Python is gone. Point Form Studio at it again."
    elif platform.system() != "Linux":
        out["why"] = "TRELLIS.2 is tested on Linux only (its README); this computer runs " + platform.system() + "."
    elif not _gpu():
        out["why"] = "No NVIDIA GPU found (nvidia-smi). TRELLIS.2 needs one with at least 24 GB."
    elif not out["enabled"]:
        out["why"] = "Installed and checked (MIT). Off: turn it on in Settings › General › Engines, or `form generate enable trellis2`."
    else:
        out.update(ready=True, why=f"On: {t['folder']}, licence MIT (SHA-256 {t['licence_sha256'][:12]}…), GPU {_gpu()}.")
    out["installed"] = t or None
    return out


def providers(cfg) -> dict:
    rows = [status(cfg, pid) for pid in PROVIDERS]
    ready = [r["id"] for r in rows if r["ready"]]
    return {"providers": rows, "ready": ready, "default": None,
            "note": ("No mesh generator is set up. There is no default: set one up in Settings › General › Engines (TRELLIS.2 on "
                     "this computer, or Meshy or Tripo with your own key).") if not ready else ""}


# ---- what is sent, before every run --------------------------------------------------------------------------------

def _image_facts(image) -> dict | None:
    if not image:
        return None
    p = Path(str(image)).expanduser()
    if not p.is_file():
        raise GenerateError(f"No picture at {p}.", "Give the absolute path of a PNG, JPEG or WebP picture.")
    raw = p.read_bytes()
    return {"file": p.name, "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest(),
            "type": mimetypes.guess_type(p.name)[0] or "application/octet-stream"}


def disclose(cfg, pid: str, text: str | None = None, image=None) -> dict:
    """What a run would send and to whom, with the consent token the run needs. Sends nothing."""
    p = get(pid)
    st = status(cfg, pid)
    text = (text or "").strip()
    if len(text) > MAX_PROMPT:
        raise GenerateError(f"The description is longer than {MAX_PROMPT} characters.", "Shorten it.")
    img = _image_facts(image)
    if not text and not img:
        raise GenerateError("Give a description (text) or a picture (image).", "")
    if img is None and "text" not in p.inputs:
        raise GenerateError(f"{p.title} makes a mesh from a picture only.", "Give image=<path of a picture>.")
    if img is not None and "image" not in p.inputs:
        raise GenerateError(f"{p.title} takes a description only.", "")
    if p.kind == "local" or pid in _EXTRA:
        sends, to = [], []
        line = (f"Nothing leaves this computer: {p.title} runs here" + (" (a test fixture)." if pid in _EXTRA else
                ", on the GPU, out of Form Studio's process."))
    else:
        sends = ([f"the description ({len(text)} characters): “{text}”"] if text and img is None else []) + \
                ([f"the picture {img['file']} ({img['bytes']:,} bytes, SHA-256 {img['sha256'][:12]}…)"] if img else [])
        to = list(p.hosts)
        line = (f"Form Studio sends {', '.join(sends)} to {p.title} ({p.hosts[0]}) with your API key, and downloads the "
                f"mesh it returns. {p.title} keeps what it is sent under its own terms. The run is billed to your "
                f"{p.title} account at its prices; Form Studio does not know the price.")
    d = {"provider": pid, "title": p.title, "model": p.model, "kind": p.kind, "sends": sends, "to": to,
         "returns": "a mesh (GLB or OBJ), saved in this project's folder", "licence": p.licence, "text": line,
         "ready": st["ready"], "why": st["why"], "input": {"text": text if img is None else "", "image": img}}
    d["consent"] = hashlib.sha256(json.dumps(d, sort_keys=True).encode()).hexdigest()[:16]
    return d


# ---- running a provider --------------------------------------------------------------------------------------------

def _req(method: str, url: str, key: str, body=None, headers=None, timeout: float = 60):
    from .. import net
    data = None
    h = {"Authorization": f"Bearer {key}", **(headers or {})}
    if isinstance(body, (dict, list)):
        data = json.dumps(body).encode()
        h["Content-Type"] = "application/json"
    elif isinstance(body, bytes):
        data = body
    r = urllib.request.Request(url, data=data, method=method, headers=h)
    try:
        with net.urlopen(r, timeout=timeout) as resp:
            raw = resp.read()
    except urllib.error.HTTPError as e:
        detail = e.read()[:300].decode("utf-8", "replace")
        raise GenerateError(f"{url.split('/')[2]} answered {e.code}: {detail}", "Check your key and credits.") from None
    except (urllib.error.URLError, OSError) as e:
        raise GenerateError(net.plain_error(e, url.split("/")[2]), "Check the connection.") from None
    return json.loads(raw.decode("utf-8")) if raw[:1] in (b"{", b"[") else raw


def _download(url: str, out: Path) -> Path:
    from .. import net
    if not url.startswith("https://"):
        raise GenerateError("The provider returned a download link that is not https.", "")
    with net.urlopen(urllib.request.Request(url), timeout=300) as resp:
        out.write_bytes(resp.read())
    return out


def _data_uri(image) -> str:
    p = Path(str(image)).expanduser()
    mime = mimetypes.guess_type(p.name)[0] or "image/png"
    return f"data:{mime};base64," + base64.b64encode(p.read_bytes()).decode("ascii")


def _poll(fn, done, failed, timeout: float = RUN_TIMEOUT_S, cancelled=None):
    t0 = time.time()
    while True:
        r = fn()
        if done(r):
            return r
        if failed(r):
            raise GenerateError(f"The generator stopped: {json.dumps(r)[:300]}", "")
        if time.time() - t0 > timeout:
            raise GenerateError(f"No mesh after {timeout:.0f} s.", "Try again later; nothing was saved.")
        if cancelled and cancelled():
            raise GenerateError("Cancelled.", "Nothing was saved.", 409)
        time.sleep(POLL_S)


def _run_meshy(p: Provider, text, image, out: Path, cfg) -> Path:
    """Meshy: POST /openapi/v2/text-to-3d {mode: preview, prompt} or POST /openapi/v1/image-to-3d {image_url: data
    URI}; poll GET .../{id} until SUCCEEDED; download model_urls.glb (docs.meshy.ai)."""
    from .. import secrets
    key = secrets.value(p.secret)[0]
    base = "https://api.meshy.ai/openapi"
    if image:
        path = "/v1/image-to-3d"
        tid = _req("POST", base + path, key, {"image_url": _data_uri(image)})["result"]
    else:
        path = "/v2/text-to-3d"
        tid = _req("POST", base + path, key, {"mode": "preview", "prompt": text})["result"]
    r = _poll(lambda: _req("GET", f"{base}{path}/{tid}", key), lambda r: r.get("status") == "SUCCEEDED",
              lambda r: r.get("status") in ("FAILED", "CANCELED"))
    url = (r.get("model_urls") or {}).get("glb")
    if not url:
        raise GenerateError("Meshy finished without a GLB link.", "")
    return _download(url, out / "generated.glb")


def _run_tripo(p: Provider, text, image, out: Path, cfg) -> Path:
    """Tripo: POST /v3/generation/text-to-model {prompt, model} or upload the picture (POST /v3/files, multipart field
    "file") and POST /v3/generation/image-to-model {input: file_token, model}; poll GET /v3/tasks/{id} until success;
    download output.model_url, a GLB (developers.tripo3d.ai)."""
    from .. import secrets
    key = secrets.value(p.secret)[0]
    base = "https://openapi.tripo3d.ai/v3"
    if image:
        ip = Path(str(image)).expanduser()
        bound = "form" + uuid.uuid4().hex
        mime = mimetypes.guess_type(ip.name)[0] or "image/png"
        body = (f"--{bound}\r\nContent-Disposition: form-data; name=\"file\"; filename=\"{ip.name}\"\r\n"
                f"Content-Type: {mime}\r\n\r\n").encode() + ip.read_bytes() + f"\r\n--{bound}--\r\n".encode()
        tok = _req("POST", base + "/files", key, body, {"Content-Type": f"multipart/form-data; boundary={bound}"})
        tid = _req("POST", base + "/generation/image-to-model", key,
                   {"input": tok["data"]["file_token"], "model": p.model})["data"]["task_id"]
    else:
        tid = _req("POST", base + "/generation/text-to-model", key, {"prompt": text, "model": p.model})["data"]["task_id"]
    r = _poll(lambda: _req("GET", f"{base}/tasks/{tid}", key), lambda r: (r.get("data") or {}).get("status") == "success",
              lambda r: (r.get("data") or {}).get("status") in ("failed", "cancelled", "banned", "expired"))
    url = ((r.get("data") or {}).get("output") or {}).get("model_url")
    if not url:
        raise GenerateError("Tripo finished without a model link.", "")
    return _download(url, out / "generated.glb")


def _run_trellis(p: Provider, text, image, out: Path, cfg) -> Path:
    """TRELLIS.2 in its own environment: form/generate/trellis_run.py, run by that environment's Python from the
    TRELLIS.2 folder, writes the GLB (the README's pipeline and o_voxel export)."""
    t = settings(cfg)["trellis2"]
    script = Path(__file__).with_name("trellis_run.py")
    glb = out / "generated.glb"
    env = {**os.environ, "PYTORCH_CUDA_ALLOC_CONF": "expandable_segments:True", "OPENCV_IO_ENABLE_OPENEXR": "1"}
    try:
        r = subprocess.run([t["python"], str(script), str(Path(str(image)).expanduser()), str(glb)], cwd=t["folder"],
                           env=env, capture_output=True, text=True, timeout=RUN_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        raise GenerateError(f"TRELLIS.2 did not finish within {RUN_TIMEOUT_S:.0f} s.", "") from None
    if r.returncode != 0 or not glb.is_file():
        raise GenerateError("TRELLIS.2 failed: " + (r.stderr or r.stdout)[-600:], "Run its example.py to check the install.")
    return glb


RUNNERS = {"meshy": _run_meshy, "tripo": _run_tripo, "trellis2": _run_trellis}


def generate_mesh(st, pid: str, text: str | None = None, image=None, consent: str = "") -> dict:
    """Run a provider after the person's consent. Returns {"mesh": path, "run": id, "disclosure"}."""
    d = disclose(st.cfg, pid, text, image)
    if not d["ready"]:
        raise GenerateError(f"{d['title']} cannot run: {d['why']}", "")
    if consent != d["consent"]:
        raise GenerateError("This run needs the person's consent to what is sent.",
                            "Show disclose() to the person; pass its consent token only after they agree.", 403)
    rid = time.strftime("%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:6]
    out = Path(st.root) / ".generate" / rid
    out.mkdir(parents=True, exist_ok=True)
    runner = _EXTRA.get(pid) or RUNNERS[pid]
    mesh = runner(get(pid), d["input"]["text"] or text, image, out, st.cfg)
    rec = {"run": rid, "provider": pid, "model": d["model"], "at": time.strftime("%Y-%m-%d %H:%M:%S"),
           "sent": d["sends"], "to": d["to"], "input": d["input"], "mesh": Path(mesh).name}
    (out / "run.json").write_text(json.dumps(rec, indent=1), encoding="utf-8")
    return {"mesh": str(mesh), "run": rid, "disclosure": d, "record": rec}


# ---- the mesh to editable CAD ------------------------------------------------------------------------------------------

def _load(path: Path):
    """(V, F) welded, in the file's units, from any mesh format Form Studio reads."""
    import numpy as np

    from .. import meshformats
    from ..recon import mesh as M
    if path.suffix.lower() in (".stl", ".obj", ".3mf"):
        T, _ = M.read_triangles(path)
    else:
        got = meshformats.read(path)
        T = np.concatenate([t for _n, t in got["parts"]]) if got["parts"] else None
        if T is None or not len(T):
            raise GenerateError(f"{path.name} holds no triangles.", "")
    V, F, _ = M.weld(np.asarray(T, dtype=np.float64))
    return V, F


def to_cad(st, mesh: str, label: str, size_mm: float = DEFAULT_SIZE_MM, tolerance: float = 0.05,
           name: str = "", on_progress=None) -> dict:
    """Split a generated mesh into parts, scale it so its longest side is size_mm (a generated mesh has no real size:
    the size is assumed and the design says so), and rebuild it as one design with a part per piece."""
    from .. import multipart
    from ..recon import mesh as M
    from ..recon import partseg
    src = Path(mesh)
    V, F = _load(src)
    ext = float((V.max(0) - V.min(0)).max())
    if ext <= 0:
        raise GenerateError("The generated mesh is empty.", "")
    s = size_mm / ext
    V = (V - V.mean(0)) * s
    V[:, 2] -= V[:, 2].min()                          # on the plate
    parts = partseg.split(V, F)
    work = src.parent / "parts"
    work.mkdir(exist_ok=True)
    files, labels, rows = [], [], []
    for i, pt in enumerate(parts):
        f = work / f"part{i + 1}.stl"
        M.write_stl(f, pt["V"], pt["F"])
        files.append(str(f))
        labels.append(f"Part {i + 1}")
        row = {"part": f"Part {i + 1}", "area_share": pt["area_share"], "crease_mm": pt["crease_mm"],
               "triangles": int(len(pt["F"]))}
        try:
            from .. import triage
            t = triage.assess_mesh(f, tolerance)
            row.update({"class": t.get("class"), "triage_route": t.get("route")})
        except Exception:                                # noqa: BLE001
            pass
        rows.append(row)
    nm = name or f"Generated {label.split('/')[0]}"
    if len(files) == 1:                     # one part: the route its triage chooses (parametric, surface or mesh body)
        res = st.reconstruct(Path(files[0]), name=nm, tolerance=tolerance, on_progress=on_progress)
    else:                                   # several: one design, each part by the parametric reconstruction, which
        # keeps a part it cannot make parametric (an organic one) as its verified Layer 1 surfaces or Layer 0 solid
        res = multipart.reconstruct_parts(st, files, name=nm, tolerance=tolerance, labels=labels, on_progress=on_progress)
        for row, b in zip(rows, res.get("parts") or []):
            sm = b.get("summary") or {}
            row.update({"layer": sm.get("layer"), "editable_pct": sm.get("editable_pct"),
                        "hausdorff_mm": sm.get("hausdorff_mm")})
    pid = res["project"]
    note = (f"Generated by {label}. The mesh was split into {len(parts)} part(s) at its concave creases and rebuilt; "
            f"its size is assumed (longest side {size_mm:g} mm, scaled ×{s:.4g} from the file).")
    with st.lock(pid):
        p = st.load(pid)
        p["generated"] = {"by": label, "mesh": src.name, "run": src.parent.name, "scale": s, "size_mm": size_mm,
                          "parts": rows}
        b = p.setdefault("brief", {"text": "", "references": []})
        b["text"] = (note + " " + (b.get("text") or "")).strip()
        st.save(p)
    st.activity(pid, "generate", note[:300], by="engine")
    return {**res, "generated_by": label, "split": rows, "scale": s, "size_mm": size_mm, "note": note}


def make(st, pid: str, text: str | None = None, image=None, consent: str = "", size_mm: float = DEFAULT_SIZE_MM,
         tolerance: float = 0.05, name: str = "", on_progress=None) -> dict:
    """The whole wave: consented generation, then parts, routes and deviation maps. Returns the design."""
    g = generate_mesh(st, pid, text, image, consent)
    label = f"{pid}/{g['disclosure']['model'] or pid}"
    out = to_cad(st, g["mesh"], label, size_mm, tolerance, name, on_progress)
    return {**out, "run": g["run"], "sent": g["record"]["sent"], "to": g["record"]["to"]}

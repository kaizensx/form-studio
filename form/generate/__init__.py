RUN_TIMEOUT_S = 900.0
MAX_PROMPT = 800
DEFAULT_SIZE_MM = 80.0


class GenerateError(RuntimeError):
    def __init__(self, message: str, hint: str = "", status: int = 422):
        super().__init__(message)
        self.hint = hint
        self.status = status

    def public(self) -> dict:
        return {"message": str(self), "hint": self.hint}


@dataclass
class Provider:
    id: str
    title: str
    kind: str                     # local | hosted
    model: str
    inputs: tuple                 # ("text", "image")
    hosts: tuple                  # where requests go (hosted)
    licence: str
    licence_url: str
    requirements: str
    secret: str = ""              # the secrets.py name of its key (hosted)
    implemented: bool = True
    note: str = ""

    def public(self) -> dict:
        return {k: (list(v) if isinstance(v, tuple) else v) for k, v in self.__dict__.items() if not k.startswith("_")}



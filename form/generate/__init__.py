"""Image or words to a mesh, then the mesh to editable CAD (wave Q).

A mesh generator makes a mesh; Form Studio never takes that mesh as the design. It splits it into parts at its
concave creases (form/recon/partseg.py), triages each part (mechanical, organic or mixed), rebuilds them as one
design (one part: the route its triage chooses, parametric, surface body or mesh body; several: the parametric
reconstruction of each, which keeps a part it cannot make parametric, typically an organic one, as its verified
Layer 1 surfaces or Layer 0 solid), keeps every part's deviation map (form/recon/verify.py), and labels the design
"generated by <provider>/<model>".

Generators are opt-in, and there is no default:

  trellis2   TRELLIS.2 (Microsoft, MIT code and weights), on this computer. The person installs it themselves, in
             its own environment, from its repository (Linux, an NVIDIA GPU with at least 24 GB, CUDA 12.4, per its
             README); Form Studio is told where, reads its LICENSE, records the licence and its SHA-256, and runs it
             out of process. Nothing leaves the computer. Image to 3D only.
  meshy      Meshy's API (api.meshy.ai), on the person's own key.        Text or image.
  tripo      Tripo's API (openapi.tripo3d.ai), on the person's own key.  Text or image.
  hunyuan    Listed, not wired: the hosted Hunyuan 3D API is not implemented, and the Hunyuan 3D community licence
             does not apply in the EU, the UK and South Korea (its Territory clause). It says so and never runs.

A hosted generator runs only when the person has stored its key (Settings › Agents & models, or `form secrets set
meshy_api_key`) AND turned it on (`form generate enable meshy`, Settings › General › Engines). Before every run Form Studio
states what is sent, to which host, what comes back and that it is billed to their account (disclose()); the run
needs that statement's consent token, which the app's dialog, the CLI's question and the MCP tool's confirmation
card hand over only on the person's yes. Tests use a fixture provider (register()); no test calls a hosted API.
"""

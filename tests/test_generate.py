"""Wave Q: words or a picture to a mesh, then the mesh to an editable multi-part design.

A fixture provider stands in for every generator: it returns a known mesh (a block with a post and a ball on top,
made here with build123d). No test reaches a hosted API: form.net.urlopen is replaced by a function that fails the
test if anything tries to send. Covers: no default generator, the disclosure and its consent token, a hosted
generator that stays off without a key and without the person turning it on, the split into parts at concave
creases, the per-part reconstruction with its deviation, and the "generated by" label."""
import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from form import generate  # noqa: E402
from form.recon import mesh as M  # noqa: E402
from form.recon import partseg  # noqa: E402
from test_studio import make_studio  # noqa: E402


def fixture_mesh(path: Path) -> Path:
    import numpy as np
    from build123d import Align, Box, Cylinder, Pos, Sphere
    B = (Align.CENTER, Align.CENTER, Align.MIN)
    shape = Box(0.6, 0.4, 0.2, align=B) + Pos(0, 0, 0.2) * Cylinder(0.08, 0.3, align=B) + Pos(0, 0, 0.62) * Sphere(0.16)
    V, F = shape.tessellate(0.002, 0.2)                  # in metres, as a generator's GLB would be
    V = np.array([[p.X, p.Y, p.Z] for p in V])
    M.write_stl(path, V, np.array(F))
    return path


def no_network(*a, **k):
    raise AssertionError("a test tried to reach the network")


class Providers(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        os.environ["FORM_SECRETS"] = str(Path(self.tmp.name) / "secrets.json")
        for k in ("MESHY_API_KEY", "TRIPO_API_KEY"):
            os.environ.pop(k, None)
        self.cfg = {"data": {"dir": self.tmp.name}}

    def tearDown(self):
        os.environ.pop("FORM_SECRETS", None)
        self.tmp.cleanup()

    def test_there_is_no_default_and_nothing_is_ready(self):
        with mock.patch("form.net.urlopen", no_network):
            r = generate.providers(self.cfg)
        self.assertIsNone(r["default"])
        self.assertEqual(r["ready"], [])
        self.assertIn("No mesh generator is set up", r["note"])
        ids = {p["id"]: p for p in r["providers"]}
        self.assertEqual(set(ids), {"trellis2", "meshy", "tripo", "hunyuan"})
        self.assertIn("No Meshy API key", ids["meshy"]["why"])
        self.assertFalse(ids["hunyuan"]["implemented"])
        self.assertIn("European Union", ids["hunyuan"]["note"])
        self.assertIn("24 GB", ids["trellis2"]["requirements"])

    def test_a_key_alone_does_not_turn_a_hosted_generator_on(self):
        from form import secrets
        secrets.set_value("meshy_api_key", "msy-test-not-a-real-key")
        self.assertFalse(generate.status(self.cfg, "meshy")["ready"])
        self.assertIn("Off", generate.status(self.cfg, "meshy")["why"])
        generate.enable(self.cfg, "meshy")
        self.assertTrue(generate.status(self.cfg, "meshy")["ready"])
        generate.enable(self.cfg, "meshy", False)
        self.assertFalse(generate.status(self.cfg, "meshy")["ready"])

    def test_the_disclosure_names_what_is_sent_and_to_whom(self):
        pic = Path(self.tmp.name) / "lamp.png"
        from PIL import Image
        Image.new("RGB", (64, 64), "white").save(pic)
        with mock.patch("form.net.urlopen", no_network):
            d = generate.disclose(self.cfg, "tripo", image=pic)
            t = generate.disclose(self.cfg, "meshy", text="a desk lamp with a round shade")
        self.assertIn("openapi.tripo3d.ai", d["to"])
        self.assertIn("lamp.png", d["sends"][0])
        self.assertIn("billed to your Tripo account", d["text"])
        self.assertEqual(len(d["consent"]), 16)
        self.assertIn("a desk lamp with a round shade", t["sends"][0])
        self.assertNotEqual(d["consent"], t["consent"])
        with self.assertRaises(generate.GenerateError):
            generate.disclose(self.cfg, "trellis2", text="words only")       # image to 3D only
        with self.assertRaises(generate.GenerateError):
            generate.disclose(self.cfg, "meshy")

    def test_trellis_checkout_must_carry_its_mit_licence(self):
        root = Path(self.tmp.name) / "TRELLIS.2"
        (root / "trellis2").mkdir(parents=True)
        (root / "LICENSE").write_text("Some other licence\n")
        with self.assertRaises(generate.GenerateError):
            generate.set_trellis(self.cfg, str(root), python=sys.executable)
        (root / "LICENSE").write_text("MIT License\n\nCopyright (c) Microsoft Corporation.\n\nPermission is hereby "
                                      "granted, free of charge, to any person obtaining a copy\n")
        s = generate.set_trellis(self.cfg, str(root), python=sys.executable)
        self.assertEqual(s["installed"]["licence"], "MIT")
        self.assertEqual(len(s["installed"]["licence_sha256"]), 64)


class PartSplit(unittest.TestCase):
    def test_a_block_post_and_ball_split_into_three_closed_parts(self):
        with tempfile.TemporaryDirectory() as d:
            f = fixture_mesh(Path(d) / "g.stl")
            T, _ = M.read_triangles(f)
        V, F, _ = M.weld(T)
        parts = partseg.split(V, F)
        self.assertEqual(len(parts), 3)
        for p in parts:
            t = M.topology(p["V"], p["F"])
            self.assertTrue(t["closed"])
            self.assertEqual(t["flipped_edges"], 0)
        self.assertAlmostEqual(sum(p["area_share"] for p in parts), 1.0, places=3)


class GenerateToCad(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        os.environ["FORM_SECRETS"] = str(Path(cls.tmp.name) / "secrets.json")
        cls.st = make_studio(Path(cls.tmp.name))
        cls.mesh = fixture_mesh(Path(cls.tmp.name) / "known.stl")
        fake = generate.Provider("fixture", "Fixture", "local", "known-mesh-1", ("text", "image"), (), "test", "", "")

        def runner(p, text, image, out, cfg):
            dst = out / "generated.stl"
            dst.write_bytes(cls.mesh.read_bytes())
            return dst
        generate.register(fake, runner)

    @classmethod
    def tearDownClass(cls):
        generate.unregister("fixture")
        os.environ.pop("FORM_SECRETS", None)
        cls.st.kernel.shutdown()
        cls.tmp.cleanup()

    def test_consent_is_required(self):
        with self.assertRaises(generate.GenerateError) as cm:
            generate.generate_mesh(self.st, "fixture", text="a lamp", consent="")
        self.assertEqual(cm.exception.status, 403)

    def test_generated_mesh_becomes_an_editable_multipart_design(self):
        d = generate.disclose(self.st.cfg, "fixture", text="a lamp")
        self.assertEqual(d["sends"], [])
        with mock.patch("form.net.urlopen", no_network):
            r = generate.make(self.st, "fixture", text="a lamp", consent=d["consent"], size_mm=100)
        self.assertEqual(r["generated_by"], "fixture/known-mesh-1")
        self.assertEqual(len(r["split"]), 3)
        self.assertEqual(len(r["parts"]), 3, r.get("failed"))
        p = self.st.load(r["project"])
        self.assertEqual(p["generated"]["by"], "fixture/known-mesh-1")
        self.assertIn("Generated by fixture/known-mesh-1", p["brief"]["text"])
        self.assertAlmostEqual(p["generated"]["size_mm"], 100)
        for part in r["parts"]:
            s = part["summary"]
            self.assertIn("hausdorff_mm", s, s.keys())
            self.assertLess(s["hausdorff_mm"], 1.0)
        run = Path(self.st.root) / ".generate" / r["run"] / "run.json"
        self.assertTrue(run.is_file())


if __name__ == "__main__":
    unittest.main()
